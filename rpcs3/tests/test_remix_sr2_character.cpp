void require(bool value, const std::string& message)
{
	if (!value) throw std::runtime_error(message);
}

const sr2_character_generated::plan& find_plan(u64 hash)
{
	for (const auto& plan : sr2_character_generated::plans)
		if (plan.hash == hash) return plan;
	throw std::runtime_error("missing generated plan");
}

u32 swapped(u32 word)
{
	return ((word & 0x00FF00FFu) << 8) | ((word & 0xFF00FF00u) >> 8);
}

void put_word(std::vector<u8>& bytes, usz offset, u32 word)
{
	word = swapped(word);
	std::memcpy(bytes.data() + offset, &word, 4);
}

std::vector<u8> fixture_bytes(const shader_fixture& fixture, const colour_constants& constants, f32 fade)
{
	const auto& plan = find_plan(fixture.hash);
	usz size = 0;
	for (const auto& step : std::span(plan.steps, plan.count)) size = std::max(size, usz{step.slot} * 16 + 32);
	if (plan.alpha_tint_offset != 0xffff) size = std::max(size, usz{plan.alpha_tint_offset} + 4);
	if (plan.tint_max_guard_offset != 0xffff) size = std::max(size, usz{plan.tint_max_guard_offset} + 16);
	std::vector<u8> bytes(size);
	for (const auto& step : std::span(plan.steps, plan.count))
		for (u32 lane = 0; lane < 4; ++lane) put_word(bytes, usz{step.slot} * 16 + lane * 4, step.words[lane]);
	for (usz i = 0; i < fixture.payload_count; ++i)
	{
		const auto& payload = fixture.payloads[i];
		for (u32 lane = 0; lane < 4; ++lane)
		{
			const u32 bits = payload.constant >= 0 ? std::bit_cast<u32>(constants[payload.constant][lane])
				: payload.literal_bits[lane];
			put_word(bytes, payload.offset + lane * 4, bits);
		}
	}
	if (plan.alpha_tint_offset != 0xffff) put_word(bytes, plan.alpha_tint_offset, std::bit_cast<u32>(fade));
	if (plan.tint_max_guard_offset != 0xffff)
	{
		put_word(bytes, plan.tint_max_guard_offset, 0);
		put_word(bytes, plan.tint_max_guard_offset + 12, std::bit_cast<u32>(fade));
	}
	return bytes;
}

f32 mix(f32 a, f32 b, f32 weight) { return a + weight * (b - a); }

sr2_colour reference_ramp(f32 mask, const colour_constants& constants, u32 first, f32 start, f32 end)
{
	u32 left;
	f32 t;
	if (mask <= start) { left = first; t = mask / start; }
	else if (mask <= end) { left = first + 1; t = (mask - start) / (end - start); }
	else { left = first + 2; t = (mask - end) / (1.f - end); }
	t = std::isnan(t) ? 0.f : std::clamp(t, 0.f, 1.f);
	t = t * t * (3.f - 2.f * t);
	sr2_colour result{};
	for (u32 lane = 0; lane < 3; ++lane) result[lane] = mix(constants[left][lane], constants[left + 1][lane], t);
	return result;
}

sr2_colour reference_material(const shader_fixture& fixture, const colour_constants& constants, const texel_table& texels)
{
	const std::string_view family = fixture.family;
	sr2_colour result{};
	if (family == "sr2-skin1")
	{
		for (u32 lane = 0; lane < 3; ++lane)
			result[lane] = texels[0][lane] * (1.f + constants[1][0] * (texels[1][lane] - 1.f) * (1.f - constants[0][lane]));
		result[3] = texels[0][3];
	}
	else if (family.starts_with("sr2-hair"))
	{
		const auto first = reference_ramp(texels[1][0], constants, 0, constants[4][0], constants[4][1]);
		const auto second = reference_ramp(texels[1][0], constants, 5, constants[4][2], constants[4][3]);
		for (u32 lane = 0; lane < 3; ++lane) result[lane] = mix(first[lane], second[lane], texels[0][0] * constants[9][0]);
		result[3] = texels[1][1] * constants[11][2];
	}
	else if (family == "bb-cloth2")
	{
		for (u32 lane = 0; lane < 3; ++lane)
		{
			f32 base = 1.f + texels[0][2] * (constants[0][lane] - 1.f);
			base = mix(base, constants[1][lane], texels[0][1]);
			base = mix(base, constants[2][lane], texels[0][0]) * texels[4][lane];
			const f32 layer = constants[3][lane] + texels[1][2] * (1.f - constants[3][lane]);
			base = mix(base, texels[1][1] * layer, texels[1][0] * constants[4][0]);
			const f32 detail = .5f + constants[4][2] * (texels[3][lane] - .5f);
			base = base < .5f ? 2.f * base * detail : 1.f - 2.f * (1.f - base) * (1.f - detail);
			result[lane] = mix(base, texels[2][lane] * constants[5][lane], texels[2][3] * constants[5][3] * constants[4][1]);
		}
		result[3] = texels[4][3];
	}
	else if (family == "bb-makeup1")
	{
		for (u32 lane = 0; lane < 3; ++lane) result[lane] = mix(constants[0][lane], constants[1][lane], texels[0][0]);
		result[3] = texels[0][1] * constants[4][1];
	}
	else if (family == "bb-tattoo1")
	{
		for (u32 lane = 0; lane < 3; ++lane)
			result[lane] = 1.f - constants[1][0] * (1.f - texels[0][lane]) * (1.f - constants[0][lane]);
		result[3] = 1.f;
	}
	else throw std::runtime_error("unknown reference family");
	return result;
}

colour_constants default_constants()
{
	colour_constants constants{};
	for (u32 slot = 0; slot < constants.size(); ++slot)
		for (u32 lane = 0; lane < 4; ++lane) constants[slot][lane] = .1f + .03f * ((slot * 4 + lane) % 20);
	constants[4] = {.2f, .7f, .3f, .8f};
	return constants;
}

texel_table default_texels()
{
	texel_table texels{};
	for (auto& texel : texels) texel = {.43f, .61f, .29f, .87f};
	return texels;
}

