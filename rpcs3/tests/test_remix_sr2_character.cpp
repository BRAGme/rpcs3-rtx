		sr2_colour x{}, y{};
		require(evaluate_sr2_character(a, texels, x) && evaluate_sr2_character(b, texels, y), "colour evaluation");
		require(std::abs(x[0] - y[0]) > 1e-6f, "live colour did not change output hash=" + std::to_string(fixture.hash));
